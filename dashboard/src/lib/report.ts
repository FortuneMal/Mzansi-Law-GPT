import type { AuditResult, Finding } from "./api";
import { contractTypeLabel, toText } from "./format";

export const STATUS_LABELS: Record<Finding["status"], string> = {
  "NON-COMPLIANT": "Non-compliant",
  RISK: "Needs attention",
  COMPLIANT: "Compliant",
};

const STATUS_ORDER: Record<Finding["status"], number> = { "NON-COMPLIANT": 0, RISK: 1, COMPLIANT: 2 };

export function sortFindings(findings: Finding[]): Finding[] {
  return [...findings].sort((a, b) => (STATUS_ORDER[a.status] ?? 3) - (STATUS_ORDER[b.status] ?? 3));
}

export function countByStatus(findings: Finding[]): Record<Finding["status"], number> {
  const counts: Record<Finding["status"], number> = { "NON-COMPLIANT": 0, RISK: 0, COMPLIANT: 0 };
  for (const f of findings) if (f.status in counts) counts[f.status] += 1;
  return counts;
}

/** Builds a Markdown copy of an audit result for download. */
export function buildAuditReport(result: AuditResult): string {
  const lines = [
    "# Contract review report",
    "",
    `- Document: ${result.document_name}`,
    `- Contract type: ${contractTypeLabel(result.contract_type)}`,
    `- Reviewed: ${new Date(result.timestamp).toLocaleString()}`,
    `- Non-compliant areas: ${result.violation_count} of ${result.findings.length}`,
    "",
  ];

  for (const finding of sortFindings(result.findings)) {
    lines.push(`## ${finding.domain}: ${STATUS_LABELS[finding.status] ?? finding.status}`, "");
    const a = finding.analysis;
    if (typeof a === "object" && !a.error) {
      const sections: [string, unknown][] = [
        ["Legal basis", a.statutory_authority],
        ["What the contract says", a.contract_clause],
        ["Analysis", a.legal_analysis],
        ["In plain language", a.citizen_explanation],
        ["Suggested wording", finding.status === "COMPLIANT" ? null : a.recommended_redline],
      ];
      for (const [heading, value] of sections) {
        const text = toText(value);
        if (text) lines.push(`### ${heading}`, "", text, "");
      }
    } else {
      lines.push(toText(typeof a === "object" ? a.raw || a.error : a), "");
    }
  }

  lines.push(
    "---",
    "",
    "Generated by Mzansi Law GPT. This review is produced by an AI system using excerpts of South African legislation. It is not legal advice; consult a qualified attorney before relying on it.",
    "",
  );
  return lines.join("\n");
}

export function downloadTextFile(filename: string, contents: string, type = "text/markdown"): void {
  const url = URL.createObjectURL(new Blob([contents], { type: `${type};charset=utf-8` }));
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

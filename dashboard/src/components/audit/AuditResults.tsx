"use client";

import { Download, RotateCcw } from "lucide-react";
import { Alert } from "@/components/ui/Alert";
import { Button } from "@/components/ui/Button";
import type { AuditResult } from "@/lib/api";
import { cn } from "@/lib/cn";
import { contractTypeLabel } from "@/lib/format";
import { buildAuditReport, countByStatus, downloadTextFile, sortFindings } from "@/lib/report";
import { useAudit } from "./AuditProvider";
import { FindingCard } from "./FindingCard";

function headline(issues: number, risks: number): { title: string; tone: "danger" | "warning" | "success" } {
  if (issues > 0) {
    return { title: `${issues} ${issues === 1 ? "area is" : "areas are"} not compliant`, tone: "danger" };
  }
  if (risks > 0) {
    return { title: `${risks} ${risks === 1 ? "area needs" : "areas need"} attention`, tone: "warning" };
  }
  return { title: "No compliance issues were found", tone: "success" };
}

const TONE_BAR = { danger: "bg-danger", warning: "bg-warning", success: "bg-success" } as const;

export function AuditResults({ result }: { result: AuditResult }) {
  const { startOver } = useAudit();
  const counts = countByStatus(result.findings);
  const summary = headline(counts["NON-COMPLIANT"], counts.RISK);
  const findings = sortFindings(result.findings);

  const download = () => {
    const base = result.document_name.replace(/\.[^.]+$/, "") || "contract";
    downloadTextFile(`${base}-review.md`, buildAuditReport(result));
  };

  return (
    <div className="space-y-6">
      <section className="relative overflow-hidden rounded-2xl border border-line bg-surface p-6 shadow-card">
        <span aria-hidden className={cn("absolute inset-y-0 left-0 w-1", TONE_BAR[summary.tone])} />
        <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
          <div className="min-w-0">
            <p className="text-xs font-medium tracking-wide text-ink-subtle uppercase">Review complete</p>
            <h2 className="mt-1 font-serif text-2xl font-semibold text-ink">{summary.title}</h2>
            <p className="mt-1 truncate text-sm text-ink-muted">
              {result.document_name} · {contractTypeLabel(result.contract_type)}
            </p>
          </div>
          <div className="flex shrink-0 gap-2">
            <Button variant="secondary" size="sm" onClick={download}>
              <Download aria-hidden className="size-3.5" />
              Download report
            </Button>
            <Button variant="ghost" size="sm" onClick={startOver}>
              <RotateCcw aria-hidden className="size-3.5" />
              New review
            </Button>
          </div>
        </div>

        <dl className="mt-6 grid grid-cols-3 divide-x divide-line rounded-xl border border-line text-center">
          {(
            [
              ["Not compliant", counts["NON-COMPLIANT"], "text-danger"],
              ["Needs attention", counts.RISK, "text-warning"],
              ["Compliant", counts.COMPLIANT, "text-success"],
            ] as const
          ).map(([label, count, color]) => (
            <div key={label} className="px-2 py-3">
              <dt className="text-xs text-ink-subtle">{label}</dt>
              <dd className={cn("mt-0.5 text-xl font-semibold tabular-nums", count > 0 ? color : "text-ink-subtle")}>
                {count}
              </dd>
            </div>
          ))}
        </dl>
      </section>

      <section aria-labelledby="findings-heading" className="space-y-3">
        <h2 id="findings-heading" className="text-sm font-semibold text-ink">
          Findings by area
        </h2>
        {findings.map((finding) => (
          <FindingCard key={finding.domain} finding={finding} />
        ))}
      </section>

      <Alert>
        This review is generated by AI from excerpts of South African legislation and may miss issues or
        misread clauses. Have a qualified attorney check the contract before you rely on it.
      </Alert>
    </div>
  );
}
